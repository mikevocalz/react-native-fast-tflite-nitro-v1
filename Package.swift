// swift-tools-version: 6.4

import PackageDescription

let package = Package(
  name: "NitroTflite",
  platforms: [.iOS(.v16)]
)

// TensorFlow Lite C 2.17.0, the version the 3.0.1 podspec pinned through the
// `TensorFlowLiteC` pod. Google ships those libraries as static archives inside
// .framework bundles with no Info.plist; SwiftPM embeds such a framework and the
// app then fails validation. The release zips wrap the same archives as
// static-library xcframeworks instead (scripts/repack-tflite-xcframeworks.sh,
// reproducible from the pod tarball), so nothing gets embedded.
let tfliteRelease =
  "https://github.com/mikevocalz/react-native-fast-tflite-nitro-v1/releases/download/tensorflowlitec-2.17.0"

package.targets += [
  .binaryTarget(
    name: "TensorFlowLiteC",
    url: "\(tfliteRelease)/TensorFlowLiteC-2.17.0-static.xcframework.zip",
    checksum: "8be69f1c111016629cbfc9a66b9e4bc6c03e611e3f6b54210274ad6222dd9b47"
  ),
  .binaryTarget(
    name: "TensorFlowLiteCCoreML",
    url: "\(tfliteRelease)/TensorFlowLiteCCoreML-2.17.0-static.xcframework.zip",
    checksum: "a2c8f933d4fba80ce2fed6a783cb9ef684f50f5814aa97be257eeeb83f906bbc"
  ),
]

// The CoreML delegate ("core-ml") is linked by default. The 3.0.1 podspec made it
// opt-in through `$EnableCoreMLDelegate` in the Podfile; SwiftPM has no Podfile, so
// opt out instead with FAST_TFLITE_ENABLE_CORE_ML=0 in the environment that
// resolves the package (Xcode or xcodebuild). Without it, "core-ml" throws.
let enableCoreML = Context.environment["FAST_TFLITE_ENABLE_CORE_ML"] != "0"

var tfliteDependencies: [Target.Dependency] = ["TensorFlowLiteC"]
if enableCoreML {
  tfliteDependencies.append("TensorFlowLiteCCoreML")
}

addNitrogenTargets(
  to: package,
  dependencies: tfliteDependencies,
  cxxSettings: [.define("FAST_TFLITE_ENABLE_CORE_ML", to: enableCoreML ? "1" : "0")]
)

// TensorFlowLiteC is a static C++ framework (the pod declared `libraries: "c++"`),
// and the CoreML delegate calls into CoreML (the pod weak-linked it).
for target in package.targets where target.name == "NitroTfliteCxx" {
  var linkerSettings = target.linkerSettings ?? []
  linkerSettings.append(.linkedLibrary("c++"))
  if enableCoreML {
    linkerSettings.append(.linkedFramework("CoreML"))
  }
  target.linkerSettings = linkerSettings
}

